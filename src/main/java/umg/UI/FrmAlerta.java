    // MÉTODO PARA CARGAR DATOS EN LA TABLA
    private void cargarAlertas() {
        AlertaDAO dao = new AlertaDAO();
        try {
            List<Alerta> lista = dao.listar();
            DefaultTableModel modelo = (DefaultTableModel) tblAlerta.getModel();
            modelo.setRowCount(0);

            for (Alerta a : lista) {
                modelo.addRow(new Object[]{
                    a.getIdAlerta(),
                    a.getNumeroAlerta(),
                    a.getIdEstudiante(),
                    a.getIdUsuarioResp(),
                    a.getFecha(),
                    a.getTipoAlerta(),
                    a.getMotivo(),
                    a.getPrioridad(),
                    a.getOrigenInformacion(),
                    a.getEstado(),
                    a.getObservaciones()
                });
            }
        } catch (SQLException exp) {
            JOptionPane.showMessageDialog(this, "Error al cargar alertas: " + exp.getMessage());
        }
    }

