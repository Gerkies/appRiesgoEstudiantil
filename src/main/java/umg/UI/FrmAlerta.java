    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // Validacion previa
        if (txtNumeroAlerta.getText().trim().isEmpty()
                || txtIdEstudiante.getText().trim().isEmpty()
                || txtIdUsuarioResp.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor complete al menos el Número de Alerta, ID Estudiante e ID Usuario Responsable.");
            return;
        }

        try {
            // Crear objeto modelo Alerta
            Alerta alerta = new Alerta();
            alerta.setNumeroAlerta(txtNumeroAlerta.getText().trim());
            alerta.setIdEstudiante(Integer.parseInt(txtIdEstudiante.getText().trim()));
            alerta.setIdUsuarioResp(Integer.parseInt(txtIdUsuarioResp.getText().trim()));
            alerta.setFecha(txtFecha.getText().trim().isEmpty() ? new java.text.SimpleDateFormat("yyyy-MM-dd").format(new java.util.Date()) : txtFecha.getText().trim());
            alerta.setTipoAlerta(txtTipoAlerta.getText().trim());
            alerta.setMotivo(txtMotivo.getText().trim());
            alerta.setPrioridad(txtPrioridad.getText().trim());
            alerta.setOrigenInformacion(txtOrigenInformacion.getText().trim());
            alerta.setEstado(txtEstado.getText().trim().isEmpty() ? "Pendiente de revision" : txtEstado.getText().trim());
            alerta.setObservaciones(txtObservaciones.getText().trim());

            // Crear objeto DAO e insertar
            AlertaDAO dao = new AlertaDAO();
            dao.insertar(alerta);
            JOptionPane.showMessageDialog(this, "Alerta registrada correctamente.");
            cargarAlertas();
            limpiarCampos();

        } catch (NumberFormatException exp) {
            JOptionPane.showMessageDialog(this, "Error: Los campos ID Estudiante e ID Usuario deben ser números enteros.");
        } catch (SQLException exp) {
            JOptionPane.showMessageDialog(this, "Error al guardar en la base de datos: " + exp.getMessage());
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        if (idAlerta == 0) {
            JOptionPane.showMessageDialog(this, "Por favor seleccione una alerta de la tabla para actualizar.");
            return;
        }

        try {
            Alerta alerta = new Alerta();
            alerta.setIdAlerta(idAlerta);
            alerta.setNumeroAlerta(txtNumeroAlerta.getText().trim());
            alerta.setIdEstudiante(Integer.parseInt(txtIdEstudiante.getText().trim()));
            alerta.setIdUsuarioResp(Integer.parseInt(txtIdUsuarioResp.getText().trim()));
            alerta.setFecha(txtFecha.getText().trim());
            alerta.setTipoAlerta(txtTipoAlerta.getText().trim());
            alerta.setMotivo(txtMotivo.getText().trim());
            alerta.setPrioridad(txtPrioridad.getText().trim());
            alerta.setOrigenInformacion(txtOrigenInformacion.getText().trim());
            alerta.setEstado(txtEstado.getText().trim());
            alerta.setObservaciones(txtObservaciones.getText().trim());

            AlertaDAO dao = new AlertaDAO();
            dao.actualizar(alerta);
            JOptionPane.showMessageDialog(this, "Alerta actualizada correctamente.");
            cargarAlertas();
            limpiarCampos();

        } catch (NumberFormatException exp) {
            JOptionPane.showMessageDialog(this, "Error: Verifique que los campos numéricos sean válidos.");
        } catch (SQLException exp) {
            JOptionPane.showMessageDialog(this, "Error al actualizar alerta: " + exp.getMessage());
        }
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        if (idAlerta == 0) {
            JOptionPane.showMessageDialog(this, "Por favor seleccione una alerta de la tabla para eliminar.");
            return;
        }

        int respuesta = JOptionPane.showConfirmDialog(
                this,
                "¿Está seguro de eliminar la alerta seleccionada?",
                "Confirmación de Eliminación",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.QUESTION_MESSAGE
        );

        if (respuesta == JOptionPane.YES_OPTION) {
            AlertaDAO dao = new AlertaDAO();
            try {
                dao.eliminar(idAlerta);
                JOptionPane.showMessageDialog(this, "Alerta eliminada exitosamente.");
                cargarAlertas();
                limpiarCampos();
            } catch (SQLException exp) {
                JOptionPane.showMessageDialog(this, "Error al eliminar alerta: " + exp.getMessage());
            }
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

