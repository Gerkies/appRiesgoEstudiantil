    private void btnIngresarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIngresarActionPerformed
        String username = txtUsuario.getText().trim();
        String clave = txtClave.getText().trim();
        // 1. Validar que no esten vacios
        if (username.isEmpty() || clave.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor ingrese su usuario y contraseña.", "Campos Requeridos", JOptionPane.WARNING_MESSAGE);
            return;
        }
        try {
            // 2. Autenticar mediante UsuarioDAO
            UsuarioDAO dao = new UsuarioDAO();
            Usuario usuario = dao.autenticar(username, clave);
            // 3. Evaluar respuesta
            if (usuario != null) {
                JOptionPane.showMessageDialog(
                        this,
                        "Bienvenido/a: " + usuario.getNombreCompleto() + "\nRol: " + usuario.getRol(),
                        "Acceso Concedido",
                        JOptionPane.INFORMATION_MESSAGE
                );
                // Abrir el menu principal pasando el usuario autenticado
                FrmMenuPrincipal menu = new FrmMenuPrincipal(usuario);
                menu.setLocationRelativeTo(null);
                menu.setVisible(true);
                // Cerrar la ventana de login actual
                this.dispose();
            } else {
                JOptionPane.showMessageDialog(
                        this,
                        "Usuario o contraseña incorrectos, o cuenta inactiva.",
                        "Acceso Denegado",
                        JOptionPane.ERROR_MESSAGE
                );
            }
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(
                    this,
                    "Error al conectar con la base de datos: " + ex.getMessage(),
                    "Error de Conexión",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_btnIngresarActionPerformed

