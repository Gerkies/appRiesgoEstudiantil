    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
// Validacion de campos requeridos
        if (txtFecha.getText().trim().isEmpty()
                || txtIdCurso.getText().trim().isEmpty()
                || txtIdGrupo.getText().trim().isEmpty()
                || txtIdEstudiante.getText().trim().isEmpty()
                || txtIdUsuarioDocente.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor complete los campos obligatorios: Fecha, ID Curso, ID Grupo, ID Estudiante e ID Docente.");
            return;
        }
        try {
            // Crear objeto modelo Asistencia
            Asistencia a = new Asistencia();
            a.setFecha(txtFecha.getText().trim());
            a.setIdCurso(Integer.parseInt(txtIdCurso.getText().trim()));
            a.setIdGrupo(Integer.parseInt(txtIdGrupo.getText().trim()));
            a.setIdEstudiante(Integer.parseInt(txtIdEstudiante.getText().trim()));
            a.setIdUsuarioDocente(Integer.parseInt(txtIdUsuarioDocente.getText().trim()));
            a.setEstadoAsistencia(txtEstadoAsistencia.getText().trim().isEmpty() ? "Presente" : txtEstadoAsistencia.getText().trim());
            a.setMotivo(txtMotivo.getText().trim());
            a.setObservaciones(txtObservaciones.getText().trim());
            // Insertar mediante DAO
            AsistenciaDAO dao = new AsistenciaDAO();
            dao.insertar(a);
            JOptionPane.showMessageDialog(this, "Asistencia registrada correctamente.");
            cargarAsistencias();
            limpiarCampos();
        } catch (NumberFormatException exp) {
            JOptionPane.showMessageDialog(this, "Error: Los campos de ID (Curso, Grupo, Estudiante, Docente) deben ser números enteros.");
        } catch (SQLException exp) {
            JOptionPane.showMessageDialog(this, "Error al guardar en la base de datos: " + exp.getMessage());
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        if (idAsistencia == 0) {
            JOptionPane.showMessageDialog(this, "Por favor seleccione un registro de asistencia de la tabla para actualizar.");
            return;
        }
        try {
            Asistencia a = new Asistencia();
            a.setIdAsistencia(idAsistencia);
            a.setFecha(txtFecha.getText().trim());
            a.setIdCurso(Integer.parseInt(txtIdCurso.getText().trim()));
            a.setIdGrupo(Integer.parseInt(txtIdGrupo.getText().trim()));
            a.setIdEstudiante(Integer.parseInt(txtIdEstudiante.getText().trim()));
            a.setIdUsuarioDocente(Integer.parseInt(txtIdUsuarioDocente.getText().trim()));
            a.setEstadoAsistencia(txtEstadoAsistencia.getText().trim());
            a.setMotivo(txtMotivo.getText().trim());
            a.setObservaciones(txtObservaciones.getText().trim());
            AsistenciaDAO dao = new AsistenciaDAO();
            dao.actualizar(a);
            JOptionPane.showMessageDialog(this, "Asistencia actualizada correctamente.");
            cargarAsistencias();
            limpiarCampos();
        } catch (NumberFormatException exp) {
            JOptionPane.showMessageDialog(this, "Error: Verifique que los campos de ID sean números enteros.");
        } catch (SQLException exp) {
            JOptionPane.showMessageDialog(this, "Error al actualizar en la base de datos: " + exp.getMessage());
        }
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        if (idAsistencia == 0) {
            JOptionPane.showMessageDialog(this, "Por favor seleccione un registro de asistencia de la tabla para eliminar.");
            return;
        }
        int respuesta = JOptionPane.showConfirmDialog(
                this,
                "¿Está seguro de eliminar el registro de asistencia seleccionado?",
                "Confirmación de Eliminación",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.QUESTION_MESSAGE
        );
        if (respuesta == JOptionPane.YES_OPTION) {
            AsistenciaDAO dao = new AsistenciaDAO();
            try {
                dao.eliminar(idAsistencia);
                JOptionPane.showMessageDialog(this, "Registro de asistencia eliminado exitosamente.");
                cargarAsistencias();
                limpiarCampos();
            } catch (SQLException exp) {
                JOptionPane.showMessageDialog(this, "Error al eliminar en la base de datos: " + exp.getMessage());
            }
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

    // MÉTODO PARA CARGAR DATOS EN LA TABLA
    private void cargarAsistencias() {
        AsistenciaDAO dao = new AsistenciaDAO();
        try {
            List<Asistencia> lista = dao.listar();
            DefaultTableModel modelo = (DefaultTableModel) tblAsistencia.getModel();
            modelo.setRowCount(0);
            for (Asistencia a : lista) {
                modelo.addRow(new Object[]{
                    a.getIdAsistencia(),
                    a.getFecha(),
                    a.getIdCurso(),
                    a.getIdGrupo(),
                    a.getIdEstudiante(),
                    a.getIdUsuarioDocente(),
                    a.getEstadoAsistencia(),
                    a.getMotivo(),
                    a.getObservaciones()
                });
            }
        } catch (SQLException exp) {
            JOptionPane.showMessageDialog(this, "Error al cargar asistencias: " + exp.getMessage());
        }
    }

    // MÉTODO PARA LIMPIAR CAMPOS
